#!/usr/bin/env python3
"""Writes js/version.js: the version number and the build time shown under the title.

Run it right before every commit. The number is the number of the commit about to be made (commits so
far + 1), but never less than the previous number + 1, so it always grows even when several commits were
squashed into one (as an external commit does). The time is the current time at UTC+2 (a fixed offset, as agreed with the
maintainer), written as YYYYMMDDhhmm.
"""
import datetime
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
count = int(subprocess.check_output(["git", "rev-list", "--count", "HEAD"], cwd=ROOT, text=True).strip())
now = datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(hours=2)
previous = 0
try:
    import re
    m = re.search(r"number:\s*(\d+)", (ROOT / "js" / "version.js").read_text(encoding="utf-8"))
    previous = int(m.group(1)) if m else 0
except OSError:
    pass
number, stamp = max(count + 1, previous + 1), now.strftime("%Y%m%d%H%M")
text = (
    "/* Generated by scripts/stamp-version.py before each commit. Do not edit by hand. */\n"
    "(function (PTD) {\n"
    "  PTD.version = { number: %d, stamp: \"%s\" };\n"
    "  var el = document.getElementById(\"version\");\n"
    "  if (el) {\n"
    "    el.textContent = \"V%d \\u00b7 %s\";\n"
    "    el.title = \"Version %d, built %s (UTC+2)\";\n"
    "  }\n"
    "})(window.PTD = window.PTD || {});\n"
) % (number, stamp, number, stamp, number, now.strftime("%Y-%m-%d %H:%M"))
(ROOT / "js" / "version.js").write_text(text, encoding="utf-8")
print("wrote js/version.js: V%d %s" % (number, stamp))
