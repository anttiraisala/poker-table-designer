#!/usr/bin/env python3
"""Turn blender/src/scene_template.py into js/blender-template.js so the page can write Blender scripts.

Run from anywhere. The generated file is committed; never edit it by hand.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
template = (ROOT / "blender" / "src" / "scene_template.py").read_text(encoding="utf-8")
assert template.count("\nPROFILE = {}\n") == 1 and template.count("\nPROJECT = {}\n") == 1
out = ("/* Generated by scripts/make-blender-js.py from blender/src/scene_template.py. Do not edit. */\n"
       "(function (PTD) { PTD.blenderTemplate = " + json.dumps(template) + "; })(window.PTD = window.PTD || {});\n")
(ROOT / "js" / "blender-template.js").write_text(out, encoding="utf-8")
print("wrote js/blender-template.js", len(out), "bytes")
