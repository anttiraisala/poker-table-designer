#!/usr/bin/env python3
"""Generates js/words-basic.js from data/words-basic.json (the page cannot fetch JSON from file://).
Run it after editing data/words-basic.json. Never edit js/words-basic.js by hand."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "data", "words-basic.json")
dst = os.path.join(root, "js", "words-basic.js")
with open(src, encoding="utf-8") as f:
    data = json.load(f)
body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
with open(dst, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by scripts/make-words-js.py from data/words-basic.json. Do not edit by hand. */\n")
    f.write("(function (PTD) { PTD.wordsBasic = " + body + "; })(window.PTD = window.PTD || {});\n")
print("wrote", dst)
